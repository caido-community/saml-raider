import { execFileSync, spawnSync } from "child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const CORPUS = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "packages",
  "frontend",
  "src",
  "tests",
  "c14n",
);

const STAMP = join(CORPUS, "GENERATED-BY");

const MARKER = "Generated by:";

const buildStamp = (version, count) =>
  `Exclusive canonicalization goldens.

Each NN-name.xml is an input fixture and the matching NN-name.exc is what
xmllint produced for it with --exc-c14n. c14n.golden.spec.ts asserts this
plugin's own toCanonicalXml reproduces those bytes exactly.

To regenerate, from the plugin root:

  pnpm goldens

That runs scripts/regenerate-c14n-goldens.mjs, which needs xmllint on PATH and
rewrites every .exc file plus this one. Canonical output can differ between
libxml2 releases, so regenerating moves the baseline.

${MARKER} ${version}
Fixtures: ${count}
`;

const readRecordedVersion = () => {
  if (!existsSync(STAMP)) return undefined;

  const line = readFileSync(STAMP, "utf8")
    .split("\n")
    .find((entry) => entry.startsWith(MARKER));

  return line === undefined ? undefined : line.slice(MARKER.length).trim();
};

const probe = spawnSync("xmllint", ["--version"], { encoding: "utf8" });
if (probe.status !== 0) {
  process.stderr.write("xmllint is required to regenerate the goldens\n");
  process.exit(1);
}

const version = `${probe.stdout}${probe.stderr}`.trim().replace(/\s+/g, " ");

const recorded = readRecordedVersion();
if (recorded !== undefined && recorded !== version) {
  process.stdout.write(
    `Goldens were produced by:\n  ${recorded}\nYour toolchain is:\n  ${version}\n` +
      `Canonical output can differ between libxml2 releases. Regenerate only if you intend to move the baseline.\n\n`,
  );
}

const inputs = readdirSync(CORPUS)
  .filter((name) => name.endsWith(".xml"))
  .sort();

for (const name of inputs) {
  const path = join(CORPUS, name);
  const exclusive = execFileSync("xmllint", ["--exc-c14n", path], {
    encoding: "utf8",
  });
  writeFileSync(path.replace(/\.xml$/, ".exc"), exclusive);
  process.stdout.write(`${name}: ${exclusive.length}b exclusive\n`);
}

writeFileSync(STAMP, buildStamp(version, inputs.length));

process.stdout.write(
  `\n${String(inputs.length)} fixtures canonicalized by ${version}\n`,
);
